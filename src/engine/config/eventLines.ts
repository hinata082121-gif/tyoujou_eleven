/** 大人（スタッフの役割と OB）の話し方 */
export type AdultLines = Record<StaffRole | "ob", string>;

/** だれが話すか */
export type EventSpeaker =
  /** キャプテン（チーム全体の出来事） */
  | "captain"
  /** 対象の部員の 1 人目 */
  | "target"
  /** 教えた人（OB・スタッフ・先輩）が話し、そのあと対象の部員が答える */
  | "mentor";

export interface EventLineDef {
  speaker: EventSpeaker;
  /** 地の文の代わり（無ければ出来事の文章をそのまま使う） */
  narration?: string;
  lines: Lines;
  /** mentor のとき：教えた人のせりふ（大人。先輩のときは lines を使い、答えは juniorLines） */
  adult?: AdultLines;
  /** 身についたときの答え */
  learned?: Lines;
  /** 身につかなかったときの答え */
  missed?: Lines;
}

